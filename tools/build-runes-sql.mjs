/**
 * Writes server/death-muffin/backend/migrations/024-relic-runes.sql from server/rules/content/runes.ts: the `rune` item type and the eleven
 * Relic rune items. There is no socket table: a socketed rune is a reserved inventory row (slots 130-134, server/rules/gameplay/runeRules.ts).
 *   node tools/build-runes-sql.mjs          (write)
 *   node tools/build-runes-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent: the ALTER restates the full enum (a no-op once 'rune' is in it) and the rows are INSERT IGNORE, so re-running changes nothing.
 * The enum list is the live one of 2026-10-02 plus 'rune'; if the live column has gained a value since, add it here before deploying.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/024-relic-runes.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'server/rules/content/runes.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const ITEM_COLS = 'id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size';

export async function render() {
  const { RUNES, RUNE_ORDER } = await load();
  const lines = [
    "-- 024-relic-runes.sql — Relic runes: socketable spell modifiers for the five necromancer rites. Adds the 'rune' item type and eleven rune items",
    '-- (stackable to 99). A socketed rune is an ordinary inventory row in reserved slot 130-134 with equipped_slot = \'rune_<rite>\' (no new table).',
    '-- GENERATED by tools/build-runes-sql.mjs from server/rules/content/runes.ts. Do not edit by hand.',
    '-- Additive and idempotent: the MODIFY restates the whole enum (a no-op when it already ends in rune), the rows are INSERT IGNORE.',
    '',
    "ALTER TABLE items MODIFY COLUMN item_type ENUM('weapon','armor_head','armor_chest','armor_legs','armor_feet','armor_hands','offhand','ring','trinket','material','consumable','rune') CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL;",
    '',
  ];
  for (const id of RUNE_ORDER) {
    const r = RUNES[id];
    lines.push(`INSERT IGNORE INTO items (${ITEM_COLS}) VALUES (${[id, r.name, r.rarity, 'rune', null, 0, '{}', id, r.sell, 0, null, 1, 99].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-runes-sql.mjs`);
      process.exit(1);
    }
    console.log('024-relic-runes.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
