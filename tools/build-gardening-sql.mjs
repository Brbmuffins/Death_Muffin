/**
 * Writes server/death-muffin/backend/migrations/007-gardening.sql from server/rules/content/gardening.ts (Grave Gardening), so the server's
 * items can't drift from the client and the offline mock.
 *   node tools/build-gardening-sql.mjs          (write)
 *   node tools/build-gardening-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent: INSERT IGNORE / CREATE TABLE IF NOT EXISTS.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/007-gardening.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'server/rules/content/gardening.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function render() {
  const { GARDEN_ITEMS } = await load();
  const lines = [
    '-- 007-gardening.sql — Grave Gardening: the seeds, herbs and saplings, and the personal plots.',
    '-- GENERATED by tools/build-gardening-sql.mjs from server/rules/content/gardening.ts. Do not edit by hand.',
    '-- Additive and idempotent: re-running it changes nothing.',
    '',
    'CREATE TABLE IF NOT EXISTS garden_plots (',
    '  character_id INT UNSIGNED NOT NULL,',
    '  plot         VARCHAR(8) NOT NULL,',
    '  seed_id      VARCHAR(64) NULL,',
    '  planted_at   BIGINT UNSIGNED NOT NULL DEFAULT 0,',
    '  ready_at     BIGINT UNSIGNED NOT NULL DEFAULT 0,',
    '  composted    TINYINT(1) NOT NULL DEFAULT 0,',
    '  PRIMARY KEY (character_id, plot),',
    '  CONSTRAINT fk_garden_character FOREIGN KEY (character_id) REFERENCES characters (id) ON DELETE CASCADE',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
  ];
  for (const [id, it] of Object.entries(GARDEN_ITEMS)) {
    lines.push(`INSERT IGNORE INTO items (id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size) VALUES (${[
      id, it.name, it.rarity, 'material', null, 0, '{}', null, it.sell, 0, null, it.stack > 1 ? 1 : 0, it.stack,
    ].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-gardening-sql.mjs`);
      process.exit(1);
    }
    console.log('007-gardening.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
