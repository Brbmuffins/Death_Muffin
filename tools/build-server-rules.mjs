/**
 * Bundles src/gameplay/necroRules.ts (+ the content it imports) into a plain
 * CommonJS module the Node auth server can `require`:
 *   server/vps-handoff/necro-progress/necro-rules.cjs
 * Run after changing prices, boons, Ascension or unlock thresholds:
 *   npm run build:server-rules
 * `--check` exits 1 if the committed copy is stale (used by the unit test).
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/vps-handoff/necro-progress/necro-rules.cjs');

export async function bundleRules() {
  const res = await build({
    entryPoints: [join(root, 'src/gameplay/necroRules.ts')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    write: false,
    legalComments: 'none',
    banner: {
      js: '// GENERATED by tools/build-server-rules.mjs from src/gameplay/necroRules.ts — do not edit by hand.\n// Necromancer progression rules shared by the web client and the auth server.',
    },
  });
  return res.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleRules();
  if (process.argv.includes('--check')) {
    const current = (() => {
      try {
        return readFileSync(OUT, 'utf8');
      } catch {
        return '';
      }
    })();
    if (current !== text) {
      console.error('necro-rules.cjs is stale — run `npm run build:server-rules`');
      process.exit(1);
    }
    console.log('necro-rules.cjs is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${text.length} bytes)`);
  }
}
