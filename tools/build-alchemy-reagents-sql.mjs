/**
 * Writes server/death-muffin/backend/migrations/014-alchemy-reagents.sql from src/content/reagents.ts: the mob reagents, zone
 * herbs and seeds, boss ichors, the new brews and their Workbench recipes. Migration 009 (alchemy.ts) is already applied live and
 * is never regenerated with these rows; everything new lives here.
 *   node tools/build-alchemy-reagents-sql.mjs          (write)
 *   node tools/build-alchemy-reagents-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent SQL: INSERT IGNORE everywhere, safe to re-run. Apply order: 013 (necro weapons) then 014.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/014-alchemy-reagents.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'src/content/reagents.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

const ITEM_COLS = 'id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size';

export async function render() {
  const { REAGENT_ITEMS, REAGENT_BREW_ITEMS, REAGENT_RECIPES } = await load();
  const lines = [
    '-- 014-alchemy-reagents.sql — Reagents and new brews: mob reagents (Grave Dust, Wraith Ectoplasm, Plague Bile, Cinder Ash),',
    '-- the zone herbs and seeds (Rot-cap, Ash-bloom), one boss ichor per area boss, eleven new elixirs and tonics, and their',
    '-- Alchemy recipes. Migration 009 is untouched; apply AFTER 013 (necro weapons).',
    '-- GENERATED by tools/build-alchemy-reagents-sql.mjs from src/content/reagents.ts. Do not edit by hand.',
    '-- Additive and idempotent (INSERT IGNORE): re-running it changes nothing.',
    '',
  ];
  for (const [id, it] of Object.entries(REAGENT_ITEMS)) {
    lines.push(`INSERT IGNORE INTO items (${ITEM_COLS}) VALUES (${[id, it.name, it.rarity, 'material', null, 0, '{}', null, it.sell, 0, null, 1, it.stack].map(q).join(', ')});`);
  }
  lines.push('');
  for (const [id, it] of Object.entries(REAGENT_BREW_ITEMS)) {
    lines.push(`INSERT IGNORE INTO items (${ITEM_COLS}) VALUES (${[id, it.name, it.rarity, 'consumable', null, 0, JSON.stringify(it.stat), null, it.sell, 1, null, 1, it.stack].map(q).join(', ')});`);
  }
  lines.push('');
  for (const [id, name, prof, level, result, qty, ings] of REAGENT_RECIPES) {
    lines.push(`INSERT IGNORE INTO recipes (id, name, profession_id, skill_level_required, result_item_id, recipe_type, craft_time_seconds, result_quantity) VALUES (${[
      id, name, prof, level, result, 'craft', 4, qty,
    ].map(q).join(', ')});`);
    for (const [item, n] of ings) lines.push(`INSERT IGNORE INTO recipe_ingredients (recipe_id, item_id, quantity) VALUES (${[id, item, n].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-alchemy-reagents-sql.mjs`);
      process.exit(1);
    }
    console.log('014-alchemy-reagents.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
