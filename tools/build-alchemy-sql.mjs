/**
 * Writes server/death-muffin/backend/migrations/009-alchemy.sql from src/content/alchemy.ts (Alchemy), so the server's items and
 * recipes can't drift from the client and the offline mock.
 *   node tools/build-alchemy-sql.mjs          (write)
 *   node tools/build-alchemy-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent SQL: INSERT IGNORE everywhere, safe to re-run.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/009-alchemy.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'src/content/alchemy.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function render() {
  const { ALCHEMY_ITEMS, ALCHEMY_RECIPES } = await load();
  const lines = [
    '-- 009-alchemy.sql — Alchemy: herb potions at the Workbench. Recipes use the new `alchemy` profession id, which the server',
    '-- allows from this release (server.js PROFESSION_NAMES). The existing flasks keep their rows; this adds two new potions and the recipes.',
    '-- GENERATED by tools/build-alchemy-sql.mjs from src/content/alchemy.ts. Do not edit by hand.',
    '-- Additive and idempotent (INSERT IGNORE): re-running it changes nothing.',
    '',
  ];
  for (const [id, it] of Object.entries(ALCHEMY_ITEMS)) {
    lines.push(`INSERT IGNORE INTO items (id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size) VALUES (${[
      id, it.name, it.rarity, 'consumable', null, 0, JSON.stringify(it.stat), null, it.sell, 1, null, 1, it.stack,
    ].map(q).join(', ')});`);
  }
  lines.push('');
  for (const [id, name, prof, level, result, qty, ings] of ALCHEMY_RECIPES) {
    lines.push(`INSERT IGNORE INTO recipes (id, name, profession_id, skill_level_required, result_item_id, recipe_type, craft_time_seconds, result_quantity) VALUES (${[
      id, name, prof, level, result, 'craft', 4, qty,
    ].map(q).join(', ')});`);
    for (const [item, n] of ings) lines.push(`INSERT IGNORE INTO recipe_ingredients (recipe_id, item_id, quantity) VALUES (${[id, item, n].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-alchemy-sql.mjs`);
      process.exit(1);
    }
    console.log('009-alchemy.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
