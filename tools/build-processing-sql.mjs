/**
 * Writes server/death-muffin/backend/migrations/004-processing.sql from src/content/processing.ts
 * (Professions G6), so the server's items/recipes can't drift from the client and the offline mock.
 *   node tools/build-processing-sql.mjs          (write)
 *   node tools/build-processing-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent SQL: INSERT IGNORE everywhere, safe to re-run.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/004-processing.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'src/content/processing.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  const url = 'data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64');
  return import(url);
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function render() {
  const { PROCESSING_ITEMS, PROCESSING_RECIPES, MEALS } = await load();
  const lines = [
    '-- 004-processing.sql — Professions G6 (carpentry, cooking, bonework, gathering tools).',
    '-- GENERATED by tools/build-processing-sql.mjs from src/content/processing.ts. Do not edit by hand.',
    '-- Additive and idempotent (INSERT IGNORE): re-running it changes nothing.',
    '',
  ];
  for (const [id, it] of Object.entries(PROCESSING_ITEMS)) {
    const tool = id.startsWith('tool_');
    const meal = MEALS[id];
    const stat = tool ? { tool: id.split('_')[1], tier: null } : meal ? { effect: 'hp_regen_pct', value: meal.healFrac, duration: meal.seconds } : {};
    if (tool) stat.tier = ['copper', 'iron', 'silver', 'steel', 'hell', 'moon'].indexOf(id.split('_')[2]) + 1;
    lines.push(`INSERT IGNORE INTO items (id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size) VALUES (${[
      id, it.name, it.rarity, it.kind, null, 0, JSON.stringify(stat), null, it.sell, 1, null, it.stack > 1 ? 1 : 0, it.stack,
    ].map(q).join(', ')});`);
  }
  lines.push('');
  for (const [id, name, prof, level, result, qty, ings] of PROCESSING_RECIPES) {
    const type = id.startsWith('smith_') || id.startsWith('brew_') ? 'craft' : 'smelt';
    lines.push(`INSERT IGNORE INTO recipes (id, name, profession_id, skill_level_required, result_item_id, recipe_type, craft_time_seconds, result_quantity) VALUES (${[
      id, name, prof, level, result, type, type === 'craft' ? 4 : 2, qty,
    ].map(q).join(', ')});`);
    for (const [item, n] of ings) lines.push(`INSERT IGNORE INTO recipe_ingredients (recipe_id, item_id, quantity) VALUES (${[id, item, n].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-processing-sql.mjs`);
      process.exit(1);
    }
    console.log('004-processing.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
