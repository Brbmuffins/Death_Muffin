/**
 * Writes server/death-muffin/backend/migrations/010-cosmetics.sql from src/content/cosmetics.ts (capes and pets), so the server's
 * charm items can't drift from the client and the offline mock.
 *   node tools/build-cosmetics-sql.mjs          (write)
 *   node tools/build-cosmetics-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Idempotent: INSERT IGNORE / CREATE TABLE IF NOT EXISTS.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/010-cosmetics.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'src/content/cosmetics.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function render() {
  const { CHARM_ITEMS } = await load();
  const lines = [
    '-- 010-cosmetics.sql — capes and pets: what you have chosen to wear, the companions you have adopted, and the pet charms.',
    '-- Capes are unlocked by skill levels (computed live from `professions`), so only the choice is stored.',
    '-- GENERATED by tools/build-cosmetics-sql.mjs from src/content/cosmetics.ts. Do not edit by hand.',
    '-- Additive and idempotent: re-running it changes nothing.',
    '',
    'CREATE TABLE IF NOT EXISTS character_cosmetics (',
    '  character_id INT UNSIGNED NOT NULL PRIMARY KEY,',
    '  cape         VARCHAR(48) NULL,',
    '  pet          VARCHAR(48) NULL,',
    '  CONSTRAINT fk_cosmetics_character FOREIGN KEY (character_id) REFERENCES characters (id) ON DELETE CASCADE',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
    'CREATE TABLE IF NOT EXISTS character_pets (',
    '  character_id INT UNSIGNED NOT NULL,',
    '  pet_id       VARCHAR(48) NOT NULL,',
    '  adopted_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,',
    '  PRIMARY KEY (character_id, pet_id),',
    '  CONSTRAINT fk_pets_character FOREIGN KEY (character_id) REFERENCES characters (id) ON DELETE CASCADE',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
  ];
  for (const [id, it] of Object.entries(CHARM_ITEMS)) {
    lines.push(`INSERT IGNORE INTO items (id, name, rarity, item_type, equipment_slot, two_handed, stat_bonus, icon_id, sell_value, crafted, modifiers, stackable, max_stack_size) VALUES (${[
      id, it.name, it.rarity, 'material', null, 0, '{}', null, it.sell, 0, null, 0, 1,
    ].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-cosmetics-sql.mjs`);
      process.exit(1);
    }
    console.log('010-cosmetics.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
