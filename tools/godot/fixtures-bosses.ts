let total = 0;
for (const s of scenarios) {
  const t = run(s);
  total += t.length;
  const phases = new Set(t.map((x: any) => x.boss.phase));
  const events = t.reduce((n: number, x: any) => n + x.log.length, 0);
  console.log(`${s.name}: ${t.length} ticks, ${events} log entries, phases ${[...phases].join(',')}, final hp ${(t[t.length - 1] as any).boss.hp > 0 ? 'alive' : 'dead'}`);
}
