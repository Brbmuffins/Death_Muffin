const OUT = 'godot/tests/bosses/fixtures';
mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) if (f.endsWith('.json')) rmSync(`${OUT}/${f}`);

type Log = Record<string, unknown>;

/** The subset of WorldSim a BossBrain touches. Every entity is a plain object, like the real sim's. */
class StubWorld {
  time = 0;
  difficulty: string;
  vowFx = { echoes: 0 };
  players = new Map<string, PlayerBody>();
  enemies = new Map<number, any>();
  thralls = new Map<number, any>();
  corpses = new Map<number, any>();
  zones = new Map<number, any>();
  cover: CoverBox[] = [];
  log: Log[] = [];
  private nextId = 1000;
  private nextZone = 1;
  constructor(readonly rand: () => number, difficulty: string, private level: number) {
    this.difficulty = difficulty;
  }
  areaLevel(_area: string) {
    return this.level;
  }
  emit(ev: unknown) {
    this.log.push({ k: 'emit', ev: JSON.parse(JSON.stringify(ev)) });
  }
  spawnEnemy(def: string, area: string, x: number, z: number, elite: boolean, rising = true) {
    const e = { id: this.nextId++, def, area, x, z, elite, hp: 100, maxHp: 100, state: 'idle' };
    this.enemies.set(e.id, e);
    this.log.push({ k: 'spawn', id: e.id, def, area, x, z, elite, rising });
    return e;
  }
  addHostilePool(x: number, z: number, r: number, dps: number, seconds: number) {
    this.log.push({ k: 'hostilePool', x, z, r, dps, seconds });
    const zone = { id: this.nextZone++, kind: 'toxic', x, z, r, until: this.time + seconds, hostile: true };
    this.zones.set(zone.id, zone);
    return zone;
  }
  emberPool(x: number, z: number, r: number, seconds: number, dps: number) {
    this.log.push({ k: 'emberPool', x, z, r, seconds, dps });
    const zone = { id: this.nextZone++, kind: 'ember', x, z, r, until: this.time + seconds, hostile: true };
    this.zones.set(zone.id, zone);
    return zone;
  }
  killThrall(t: any, reason: string) {
    if (!this.thralls.delete(t.id)) return;
    this.log.push({ k: 'killThrall', id: t.id, reason });
  }
  removeCorpse(c: any, reason: string) {
    if (!this.corpses.delete(c.id)) return;
    this.log.push({ k: 'rmCorpse', id: c.id, reason });
  }
  /** Zones expire like the real sim's (checked by the harness each tick). */
  expireZones() {
    for (const z of [...this.zones.values()]) if (this.time >= z.until) this.zones.delete(z.id);
  }
}


interface Cfg {
  name: string;
  boss: BossId;
  seed: number;
  difficulty: 'easy' | 'medium' | 'hard';
  level: number;
  nPlayers: number;
  empowered?: boolean;
  echoes?: number;
  ticks: number;
  dt: number | 'irregular';
  /** Fraction of boss health remaining at the end of the damage ramp (negative = defeat). */
  endRatio: number;
  /** Ticks at which an extra scripted event runs (scenario-specific, see `special`). */
  special?: (c: Ctx) => void;
  cover?: CoverBox[];
  fracture?: boolean;
  /** Tick range during which no player is in the area. */
  away?: [number, number];
}

interface Ctx {
  cfg: Cfg;
  w: StubWorld;
  brain: BossBrain;
  tick: number;
  ops: Log[];
  rng: () => number;
  walkers: { id: string; alive: boolean }[];
  /** Apply + record an op. */
  op(o: Log): void;
}

function applyOp(c: Ctx, o: Log) {
  const { w, brain } = c;
  switch (o.op) {
    case 'awaken': brain.awaken(o.by as string, !!o.empowered); break;
    case 'damage': brain.damage(o.amount as number, o.by as string, o.fracture as number); break;
    case 'stagger': brain.stagger(o.seconds as number); break;
    case 'resume': brain.resume(); break;
    case 'set_players': {
      w.players.clear();
      for (const p of o.players as PlayerBody[]) w.players.set(p.id, { ...p });
      break;
    }
    case 'kill_enemy': { const e = w.enemies.get(o.id as number); if (e) { e.hp = 0; e.state = 'dead'; } break; }
    case 'del_enemy': w.enemies.delete(o.id as number); break;
    case 'add_enemy': w.enemies.set(o.id as number, { id: o.id, def: o.def, area: o.area, x: o.x, z: o.z, elite: false, hp: o.hp, maxHp: o.hp, state: 'idle' }); break;
    case 'del_corpse': w.corpses.delete(o.id as number); break;
    case 'add_corpse': w.corpses.set(o.id as number, { id: o.id, area: o.area, x: o.x, z: o.z }); break;
    case 'add_thrall': w.thralls.set(o.id as number, { id: o.id, x: o.x, z: o.z, hp: o.hp, maxHp: o.hp, flash: 0, state: 'idle' }); break;
    case 'set_boss': Object.assign(brain.state, o.fields as object); break;
    case 'set_cover': w.cover = (o.boxes as CoverBox[]).map((b) => ({ ...b })); break;
    default: throw new Error('unknown op ' + o.op);
  }
}

function snapshotWorld(w: StubWorld) {
  const f = (m: Map<number, any>) => [...m.values()].map((e) => ({ id: e.id, hp: e.hp, maxHp: e.maxHp, state: e.state, x: e.x, z: e.z })).sort((a, b) => a.id - b.id);
  return { enemies: f(w.enemies), thralls: f(w.thralls), corpses: [...w.corpses.keys()].sort((a, b) => a - b), zones: [...w.zones.keys()].sort((a, b) => a - b) };
}

function bossSnap(b: BossBrain) {
  const s = b.state;
  return { active: s.active, x: s.x, z: s.z, facing: s.facing, hp: s.hp, maxHp: s.maxHp, phase: s.phase, state: s.state, stateT: s.stateT, flash: s.flash, fracture: s.fracture, fractureT: s.fractureT, withered: s.withered, witheredT: s.witheredT, witheredDps: s.witheredDps, level: s.level, empowered: !!s.empowered };
}

function run(cfg: Cfg) {
  const rng = mulberry32(cfg.seed);
  const prng = mulberry32(cfg.seed ^ 0x9e3779b9); // the scenario script's own randomness (not the sim's)
  const w = new StubWorld(mulberry32(cfg.seed + 1), cfg.difficulty, cfg.level);
  w.vowFx.echoes = cfg.echoes ?? 0;
  if (cfg.cover) w.cover = cfg.cover.map((b) => ({ ...b }));
  const brain = makeBossBrains(w as never)[cfg.boss];
  const def = BOSSES[cfg.boss];
  const arena = def.arena;
  const ticks: Log[] = [];
  const ctx: Ctx = { cfg, w, brain, tick: 0, ops: [], rng: prng, walkers: [] as never, op: (o) => { ctx.ops.push(o); applyOp(ctx, o); } };

  // players
  type Walker = { id: string; x: number; z: number; tx: number; tz: number; alive: boolean; speed: number };
  const walkers: Walker[] = [];
  for (let i = 0; i < cfg.nPlayers; i++) {
    const a = prng() * Math.PI * 2;
    const r = prng() * arena.r * 0.7;
    walkers.push({ id: 'p' + i, x: arena.x + Math.sin(a) * r, z: arena.z + Math.cos(a) * r, tx: arena.x, tz: arena.z, alive: true, speed: 4.5 + prng() * 2 });
  }
  ctx.walkers = walkers;
  const pickTarget = (wk: Walker) => {
    const roll = prng();
    if (roll < 0.35) { wk.tx = brain.state.x + (prng() - 0.5) * 6; wk.tz = brain.state.z + (prng() - 0.5) * 6; }
    else if (roll < 0.5 && cfg.boss === 'gravedigger') { const p = GRAVEDIGGER_PITS[Math.floor(prng() * 4)]; wk.tx = p[0]; wk.tz = p[1]; }
    else if (roll < 0.75 && cfg.boss === 'mire') { const h = FEN_HUMMOCKS[1 + Math.floor(prng() * 6)]; wk.tx = h.x + (prng() - 0.5) * 2; wk.tz = h.z + (prng() - 0.5) * 2; }
    else { const a = prng() * Math.PI * 2; const r = Math.sqrt(prng()) * arena.r * 0.95; wk.tx = arena.x + Math.sin(a) * r; wk.tz = arena.z + Math.cos(a) * r; }
  };
  const syncPlayers = (extraAreaFor?: string) => {
    const away = cfg.away && ctx.tick >= cfg.away[0] && ctx.tick < cfg.away[1];
    ctx.op({ op: 'set_players', players: away ? [] : walkers.map((wk) => ({ id: wk.id, x: wk.x, z: wk.z, alive: wk.alive, area: wk.id === extraAreaFor ? 'graves_other' : def.area })) });
  };
  const dtSeq = (): number => (cfg.dt === 'irregular' ? 0.01 + prng() * 0.12 : cfg.dt);

  for (let t = 0; t < cfg.ticks; t++) {
    ctx.tick = t;
    ctx.ops = [];
    w.log = [];
    const dt = dtSeq();
    // players walk
    for (const wk of walkers) {
      if (!wk.alive) continue;
      const dx = wk.tx - wk.x, dz = wk.tz - wk.z, d = Math.hypot(dx, dz);
      if (d < 0.5) pickTarget(wk);
      else { wk.x += (dx / d) * wk.speed * dt; wk.z += (dz / d) * wk.speed * dt; }
    }
    if (t === 0) {
      syncPlayers();
      ctx.op({ op: 'awaken', by: 'p0', empowered: !!cfg.empowered });
    } else if (t % 3 === 0 || t < 3) syncPlayers();
    // damage ramp toward the scenario's end ratio
    if (brain.state.active && t % 10 === 5) {
      const prog = t / cfg.ticks;
      const want = 1 + (cfg.endRatio - 1) * prog;
      const ratio = brain.state.hp / brain.state.maxHp;
      if (ratio > want) ctx.op({ op: 'damage', amount: (ratio - want) * brain.state.maxHp * (0.5 + prng()), by: walkers[Math.floor(prng() * walkers.length)].id, fracture: cfg.fracture && prng() < 0.5 ? 1 : 0 });
    }
    cfg.special?.(ctx);
    w.time += dt;
    w.expireZones();
    brain.update(dt);
    ticks.push({ t, dt, ops: ctx.ops, boss: bossSnap(brain), time: w.time, log: w.log.slice(), world: snapshotWorld(w) });
  }
  // world snapshots only on change, to keep the files small
  let prev = '';
  for (const tk of ticks) {
    const s = JSON.stringify(tk.world);
    if (s === prev) delete tk.world;
    else prev = s;
  }
  writeFileSync(`${OUT}/${cfg.name}.json`, JSON.stringify({ name: cfg.name, boss: cfg.boss, seed: cfg.seed, difficulty: cfg.difficulty, level: cfg.level, echoes: cfg.echoes ?? 0, cover: cfg.cover ?? [], area_level: cfg.level, ticks }) + '\n');
  return ticks;
}

