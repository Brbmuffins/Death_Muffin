/**
 * Golden fixtures for godot/sim/bosses (run: npx vite-node tools/godot/fixtures-bosses.ts).
 * Drives the REAL BossBrain classes (src/gameplay/sim/BossBrain.ts) against a minimal stub of the WorldSim surface they use
 * (StubWorld below = the boss-world view documented in godot/sim/bosses/README.md), through seeded scripted scenarios, and records
 * for every tick: the ops applied, the boss state, and an ordered log of everything the brain asked the world to do
 * (emitted events, spawns, removals, pools, thrall/corpse changes). The GDScript port must reproduce it.
 * Output: godot/tests/bosses/fixtures/<scenario>.json (gitignored, regenerated by tools/godot/gen-fixtures.sh).
 */
