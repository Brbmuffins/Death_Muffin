const scenarios: Cfg[] = [];
let seed = 100;
for (const boss of BOSS_IDS) {
  scenarios.push({ name: `${boss}_solo_full`, boss, seed: seed++, difficulty: 'medium', level: AREAS[BOSSES[boss].area].level, nPlayers: 1, ticks: 1400, dt: 0.05, endRatio: -0.1 });
  scenarios.push({ name: `${boss}_party_hard_empowered`, boss, seed: seed++, difficulty: 'hard', level: 14, nPlayers: 4, empowered: true, ticks: 1600, dt: 0.05, endRatio: -0.05, fracture: true });
  scenarios.push({ name: `${boss}_irregular_dt_easy`, boss, seed: seed++, difficulty: 'easy', level: 5, nPlayers: 2, ticks: 1500, dt: 'irregular', endRatio: 0.2, fracture: true });
  scenarios.push({
    name: `${boss}_wipe_reawaken`, boss, seed: seed++, difficulty: 'medium', level: 9, nPlayers: 2, ticks: 1000, dt: 0.05, endRatio: 0.35, away: [300, 400],
    special: (c) => {
      // everyone leaves the area at 300 (boss resets), they come back (one dead) and re-summon at 400, then it dies at 800.
      if (c.tick === 400) { c.walkers[1].alive = false; c.op({ op: 'set_players', players: c.walkers.map((wk: any) => ({ id: wk.id, x: wk.x, z: wk.z, alive: wk.alive, area: BOSSES[c.cfg.boss].area })) }); c.op({ op: 'awaken', by: 'p0', empowered: false }); }
      if (c.tick === 800) c.op({ op: 'damage', amount: 1e12, by: 'p0', fracture: 0 });
    },
  });
  scenarios.push({
    name: `${boss}_stagger_withered`, boss, seed: seed++, difficulty: 'medium', level: 12, nPlayers: 3, ticks: 1200, dt: 0.05, endRatio: 0.1, fracture: true,
    special: (c) => {
      if (c.tick % 97 === 40) c.op({ op: 'stagger', seconds: 0.4 + c.rng() * 2 });
      if (c.tick === 200 || c.tick === 700) c.op({ op: 'set_boss', fields: { withered: 3, witheredT: 6, witheredDps: c.brain.state.maxHp * 0.002 } });
      if (c.tick === 500) c.op({ op: 'resume' });
    },
  });
}
