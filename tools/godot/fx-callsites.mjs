#!/usr/bin/env node
// Generates godot/fx/CALLSITES.md: every place the web game calls an Effects / BinbunFX / necroFx function, with the enclosing
// function, the Binbun effect id when the line names one, and the DmFx call that replaces it. Run: node tools/godot/fx-callsites.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SKIP = /binbun\/godot|binbun\/shaders|__tests__|src\/graphics\/Effects\.ts|src\/graphics\/necroFx\.ts|fxProbe|binbun\/BinbunFX|binbun\/presets|binbun\/gallery/;
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : p.endsWith('.ts') ? [p] : []; });
const MAP = {
  emit: 'DmFx.emit({...})', emitSmoke: 'DmFx.emit_smoke({...})', decal: 'DmFx.decal({...})', flash: 'DmFx.flash({...})', orbit: 'DmFx.orbit({...})',
  beam: 'DmFx.beam(a, b, color, width, duration)', spikeRing: 'DmFx.spike_ring(x, z, r, count, life)', spikeLine: 'DmFx.spike_line(x, z, dx, dz, len, width, seq)',
  graveHands: 'DmFx.grave_hands(x, z, r, count, dur)', boneOrbit: 'DmFx.bone_orbit({...})', projectile: 'DmFx.projectile({...})', lightFlash: 'DmFx.light_flash(pos, color, intensity, life)',
  danger: 'DmFx.danger(callable)', partnerBinbun: 'DmFx.partner_binbun(opts)', playFx: 'DmFx.play(id, pos, opts)', bb: 'DmFx.play(id, pos, opts)  (the local bb() wrapper = playFx + partnerBinbun)', spawn: 'DmFx.play(id, pos, opts)',
  boneSplinters: 'DmFx.motifs.bone_splinters', graveDirt: 'DmFx.motifs.grave_dirt', soulMotes: 'DmFx.motifs.soul_motes', rotSpores: 'DmFx.motifs.rot_spores',
  mistWhisper: 'DmFx.motifs.mist_whisper', skullWisps: 'DmFx.motifs.skull_wisps', skullRing: 'DmFx.motifs.skull_ring', spiritWisps: 'DmFx.motifs.spirit_wisps',
  spectralHands: 'DmFx.motifs.spectral_hands', crackedGround: 'DmFx.motifs.cracked_ground', slashMark: 'DmFx.motifs.slash_mark',
};
const CALL = /(?:\b(?:effects|fx|e)\.|\bthis\.effects\.)(emit|emitSmoke|decal|flash|orbit|beam|spikeRing|spikeLine|graveHands|boneOrbit|projectile|lightFlash|danger|partnerBinbun)\(|\b(playFx|bb)\(|binbun\.(spawn)\(|\b(boneSplinters|graveDirt|soulMotes|rotSpores|mistWhisper|skullWisps|skullRing|spiritWisps|spectralHands|crackedGround|slashMark)\(/;
const FN = /^\s*(?:(?:private|public|protected|static|async|export)\s+)*(?:function\s+)?([A-Za-z_$][\w$]*)\s*(?:<[^>]*>)?\s*\([^;]*\)\s*(?::\s*[^={]+)?\s*\{\s*$/;
const ids = JSON.parse(readFileSync('godot/assets/fx/fx_data.json', 'utf8')).catalog.effects;
const rows = [];
for (const file of walk('src').filter((f) => !SKIP.test(f)).sort()) {
  const lines = readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const m = CALL.exec(line);
    if (!m || /^\s*(\/\/|\*)/.test(line)) return;
    const method = m[1] || m[2] || m[3] || m[4];
    let fn = '';
    for (let k = i; k >= 0 && k > i - 400; k--) {
      const f = FN.exec(lines[k]);
      if (f && !/^(if|for|while|switch|catch|return)$/.test(f[1])) { fn = f[1]; break; }
    }
    const id = (line.match(/'([a-z_0-9]+)'/g) || []).map((s) => s.slice(1, -1)).find((s) => ids.includes(s)) || '';
    const tex = (line.match(/fx\.(\w+)\(\)|fxImage\('(\w+)'\)/) || []).slice(1).find(Boolean) || '';
    rows.push({ file: file.replace(/^src\//, ''), line: i + 1, fn, method, id, tex });
  });
}
const out = ['# Web call sites -> DmFx (generated by tools/godot/fx-callsites.mjs; do not hand-edit)', '', `${rows.length} call sites. Columns: file:line, enclosing function, web call, Binbun effect id or sprite texture named on the line, DmFx replacement. Coordinates map 1:1 (x, z ground plane, y up); \`{x,y,z}\` literals become Vector3 / dictionary keys.`, ''];
let cur = '';
for (const r of rows) {
  if (r.file !== cur) {
    cur = r.file;
    out.push('', `## ${cur}`, '', '| line | function | web call | id / texture | DmFx |', '|---|---|---|---|---|');
  }
  out.push(`| ${r.line} | ${r.fn || '(top level)'} | \`${r.method}\` | ${r.id || r.tex || ''} | ${MAP[r.method]} |`);
}
writeFileSync('godot/fx/CALLSITES.md', out.join('\n') + '\n');
console.log(`fx-callsites: ${rows.length} call sites in ${new Set(rows.map((r) => r.file)).size} files`);
