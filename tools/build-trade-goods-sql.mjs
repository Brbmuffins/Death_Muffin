/**
 * Writes server/death-muffin/backend/migrations/028-trade-goods-recipes.sql from src/content/tradeGoods.ts, so the server's recipes
 * can't drift from the client and the offline mock.
 *   node tools/build-trade-goods-sql.mjs          (write)
 *   node tools/build-trade-goods-sql.mjs --check  (exit 1 if the committed file is stale; the tests run this)
 * Recipes + ingredients only, every item row already exists. Idempotent: INSERT IGNORE, safe to re-run.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'server/death-muffin/backend/migrations/028-trade-goods-recipes.sql');

async function load() {
  const res = await build({ entryPoints: [join(root, 'src/content/tradeGoods.ts')], bundle: true, platform: 'node', format: 'esm', write: false });
  return import('data:text/javascript;base64,' + Buffer.from(res.outputFiles[0].text).toString('base64'));
}

const q = (v) => (typeof v === 'number' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);

export async function render() {
  const { TRADE_GOODS_RECIPES } = await load();
  const lines = [
    '-- 028-trade-goods-recipes.sql — Workbench recipes for the old sell-only trade goods: Bronze Warden Kit, Tin Augment, Garnet Ring, Opal Flask.',
    '-- Recipe and ingredient rows only: every result and ingredient item already exists, no schema change, nothing deleted. Apply after 027.',
    '-- GENERATED by tools/build-trade-goods-sql.mjs from src/content/tradeGoods.ts. Do not edit by hand.',
    '-- Additive and idempotent (INSERT IGNORE): re-running it changes nothing.',
    '',
  ];
  for (const [id, name, prof, level, result, qty, ings] of TRADE_GOODS_RECIPES) {
    lines.push(`INSERT IGNORE INTO recipes (id, name, profession_id, skill_level_required, result_item_id, recipe_type, craft_time_seconds, result_quantity) VALUES (${[
      id, name, prof, level, result, 'craft', 4, qty,
    ].map(q).join(', ')});`);
    for (const [item, n] of ings) lines.push(`INSERT IGNORE INTO recipe_ingredients (recipe_id, item_id, quantity) VALUES (${[id, item, n].map(q).join(', ')});`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await render();
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (cur !== sql) {
      console.error(`${OUT} is stale — run node tools/build-trade-goods-sql.mjs`);
      process.exit(1);
    }
    console.log('028-trade-goods-recipes.sql is up to date');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`);
  }
}
